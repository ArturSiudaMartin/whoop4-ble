import org.junit.Test
import kotlin.math.abs

/**
 * Decoder parity with the Python reference. The vectors (src/test/resources/golden/vectors.json) are
 * generated by tools/golden.py, which runs src/whoop4/packet.py and reader.py on real captures from
 * docs/SAMPLE_SESSION.md, hand-built edge cases and a seeded random sweep. Regenerate with
 * `python -I tools/golden.py` whenever the Python reference changes.
 */
class GoldenVectorsTest {
    private val root: JsonObject = Json.parseToJsonElement(
        javaClass.getResource("/golden/vectors.json")!!.readText(),
    ).jsonObject

    private fun hex(s: String) = ByteArray(s.length / 2) { s.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
    private fun JsonObject.opt(k: String): JsonElement? = this[k]?.takeIf { it !is JsonNull }

    private fun assertClose(msg: String, expected: Double, actual: Double, tol: Double) =
        assertTrue("$msg: expected $expected, got $actual", abs(expected - actual) <= tol)

    @Test fun framesMatchPython() {
        val frames = root["frames"]!!.jsonArray
        assertTrue("expected the full vector set", frames.size >= 300)
        var historical = 0; var events = 0
        for (f in frames) {
            val o = f.jsonObject
            val name = o["name"]!!.jsonPrimitive.content
            val exp = o["expect"]!!.jsonObject
            val pkt = Packet.parse(hex(o["hex"]!!.jsonPrimitive.content))

            val expPkt = exp.opt("packet")
            if (expPkt == null) { assertNull("$name: packet should be rejected", pkt); continue }
            assertNotNull("$name: packet", pkt); pkt!!
            val ep = expPkt.jsonObject
            assertEquals("$name type", ep["type"]!!.jsonPrimitive.int, pkt.type)
            assertEquals("$name seq", ep["seq"]!!.jsonPrimitive.int, pkt.seq)
            assertEquals("$name cmd", ep["cmd"]!!.jsonPrimitive.int, pkt.cmd)
            assertEquals("$name data", ep["data"]!!.jsonPrimitive.content, pkt.data.toHex())

            if ("historical" in exp) { checkHistorical(name, exp.opt("historical")?.jsonObject, HistoricalParser.parse(pkt.data)); historical++ }
            if ("event" in exp) { checkEvent(name, exp["event"]!!.jsonObject, EventParser.parse(pkt)!!); events++ }
            if ("metadata" in exp) {
                val m = exp["metadata"]!!.jsonObject; val k = MetadataParser.parse(pkt)!!
                assertEquals("$name start", m.opt("start_offset")?.jsonPrimitive?.long, k.startOffset)
                assertEquals("$name end", m.opt("end_offset")?.jsonPrimitive?.long, k.endOffset)
                assertEquals("$name trim", m.opt("trim_offset")?.jsonPrimitive?.long, k.trim)
            }
            if ("clock" in exp) {
                val c = exp["clock"]!!.jsonObject; val k = ClockParser.parse(pkt)!!
                assertEquals("$name hw_rtc", c.opt("hw_rtc")?.jsonPrimitive?.long, k.hwRtc)
                assertEquals("$name subsec", c.opt("subsec_ticks")?.jsonPrimitive?.int, k.subsecTicks)
            }
            if ("console" in exp) assertEquals("$name console", exp["console"]!!.jsonPrimitive.content, ConsoleParser.parse(pkt))
        }
        assertTrue("historical vectors exercised", historical > 150)
        assertTrue("event vectors exercised", events > 15)
    }

    private fun checkHistorical(name: String, exp: JsonObject?, got: HistoricalRecord?) {
        if (exp == null) { assertNull("$name: record should be rejected", got); return }
        assertNotNull("$name: record", got); got!!
        assertEquals("$name timestamp", exp["timestamp"]!!.jsonPrimitive.long, got.timestamp)
        assertEquals("$name subsec", exp["subsec"]!!.jsonPrimitive.int, got.subsec)
        assertEquals("$name hr", exp["hr"]!!.jsonPrimitive.int, got.hr)
        val rr = exp.opt("rr_ms")?.jsonArray?.map { it.jsonPrimitive.int } ?: emptyList()
        assertEquals("$name rr", rr, got.rrMs)
        val acc = exp.opt("accel")?.jsonArray
        if (acc == null) assertNull("$name accel", got.accel)
        else {
            val a = got.accel
            assertNotNull("$name accel", a); a!!
            // Python rounds to 4 decimals; Bloop keeps the raw float32.
            listOf(a.x, a.y, a.z).forEachIndexed { i, v -> assertClose("$name accel[$i]", acc[i].jsonPrimitive.double, v.toDouble(), 0.5e-4 + 1e-9) }
        }
    }

    private fun checkEvent(name: String, exp: JsonObject, got: BandEvent) {
        assertEquals("$name event_type", exp["event_type"]!!.jsonPrimitive.int, got.eventType)
        assertEquals("$name _raw", exp["_raw"]!!.jsonPrimitive.content, got.rawHex)
        assertEquals("$name event", exp.opt("event")?.jsonPrimitive?.contentOrNull, got.name)
        assertEquals("$name payload_bits", exp.opt("payload_bits")?.jsonPrimitive?.contentOrNull, got.payloadBitsHex)
        val bp = exp.opt("battery_pct")?.jsonPrimitive?.double
        if (bp == null) assertNull("$name battery", got.batteryPct) else assertClose("$name battery", bp, got.batteryPct!!, 0.05)
        val st = exp.opt("skin_temp_c")?.jsonPrimitive?.double
        if (st == null) assertNull("$name skin temp", got.skinTempC) else assertClose("$name skin temp", st, got.skinTempC!!, 0.005)
    }

    @Test fun heartRateMeasurementsMatchReaderPy() {
        for (v in root["hr_measurements"]!!.jsonArray) {
            val o = v.jsonObject
            val h = o["hex"]!!.jsonPrimitive.content
            val exp = o["expect"]!!.jsonObject
            val got = HeartRateMeasurement.parse(hex(h))
            if ("error" in exp) { assertNull("$h: reference raises, Bloop returns null", got); continue }
            assertNotNull(h, got); got!!
            assertEquals("$h hr", exp["hr_bpm"]!!.jsonPrimitive.int, got.hr)
            val rr = (exp["rr_intervals_ms"] as JsonArray).map { it.jsonPrimitive.double }
            assertEquals("$h rr count", rr.size, got.rrMs.size)
            rr.zip(got.rrMs).forEach { (e, g) -> assertClose("$h rr", e, g, 0.05 + 1e-9) }   // reader.py rounds to 0.1 ms
        }
    }

    @Test fun commandFramesMatchPython() {
        for (v in root["commands"]!!.jsonArray) {
            val o = v.jsonObject
            val expected = o["hex"]!!.jsonPrimitive.content
            val got = when (val n = o["name"]!!.jsonPrimitive.content) {
                "set_clock" -> Commands.setClock(o["ts"]!!.jsonPrimitive.long)
                "get_clock" -> Commands.getClock()
                "send_historical_data" -> Commands.sendHistoricalData()
                "abort_historical_transmits" -> Commands.abortHistoricalTransmits()
                "historical_data_result" -> Commands.historicalDataResult(o["trim"]!!.jsonPrimitive.long)
                else -> error("unknown command vector $n")
            }
            assertEquals(o["name"]!!.jsonPrimitive.content, expected, got.toHex())
        }
    }

    @Test fun assemblerRebuildsFramesSplitAcrossNotifications() {
        val frames = root["frames"]!!.jsonArray.map { hex(it.jsonObject["hex"]!!.jsonPrimitive.content) }
            .filter { it.size >= 8 && FrameAssembler.isFrameStart(it) && 4 + ((it[1].toInt() and 0xFF) or ((it[2].toInt() and 0xFF) shl 8)) == it.size }
        val out = ArrayList<ByteArray>()
        val asm = FrameAssembler { out.add(it) }
        for (f in frames) f.toList().chunked(20).forEach { asm.feed(it.toByteArray()) }   // default ATT MTU payload
        assertEquals(frames.size, out.size)
        frames.zip(out).forEach { (a, b) -> assertEquals(a.toHex(), b.toHex()) }
    }

    @Test fun assemblerIgnoresStrayChunksAndSurvivesALostContinuation() {
        val out = ArrayList<String>()
        val asm = FrameAssembler { out.add(it.toHex()) }
        val a = Commands.historicalDataResult(0x12345678)   // 20-byte frame
        val b = Commands.setClock(1778539127)
        asm.feed(byteArrayOf(0xAA.toByte(), 1, 2, 3, 4))     // looks like SOF but header CRC is wrong: ignored
        asm.feed(a.copyOfRange(0, 10))                       // first half of a…
        asm.feed(b)                                          // …continuation lost; a real new frame arrives
        assertEquals(listOf(b.toHex()), out)
    }

    @Test fun consoleDetectsInvalidRtc() {
        assertEquals(32154354L, ConsoleParser.invalidRtcValue("Flash: RTC timestamp 32154354 is invalid; not saving data to flash."))
        assertNull(ConsoleParser.invalidRtcValue("BLE: Historical Dump Complete"))
    }
}
